import type { Timestamp } from "firebase/firestore";

export type TimestampLike = Timestamp | { seconds: number; nanoseconds: number };

export type FieldDomain = "agri" | "construction";

// Collection: users/{userId}
export interface UserProfile {
  uid: string;
  displayName: string;
  email: string | null;
  domain?: FieldDomain;
  defaultDomain: FieldDomain;
  zone?: string;
  locationLabel: string; // e.g., "Block C Maize Plot" or "Site Sector 4"
  onboardingCompleted?: boolean;
  isAnonymous?: boolean;
  createdAt: TimestampLike;
  updatedAt?: TimestampLike;
}

export interface LocalTriageResult {
  summary: string;
  severity: "low" | "medium" | "critical";
  confidence: number; // 0-100 confidence percentage
  immediateAction: string; // Offline first-aid / safety step (read aloud by TTS)
  extractedTags: string[]; // e.g., ["leaf-curl", "moisture-stress"]
  needsCloudDeepAudit?: boolean;
  inferenceSource: "on_device" | "in_cloud";
  processedAt: number; // Client epoch timestamp
  latencyMs?: number; // Real measured inference duration in ms
}

export interface WorkflowStep {
  phase: string;
  action: string;
  timing: string;
}

export interface CloudAuditResult {
  rootCauseAnalysis: string;
  stepByStepPlan: Array<{ step: string; completed: boolean }>;
  estimatedMaterialsOrInputs: Array<{ item: string; quantity: string }>;
  safetyOrComplianceNotes: string;
  workflowSteps?: WorkflowStep[]; // Lightweight 3-4 step visual workflow rendered in React/Tailwind
  modelUsed?: string; // Exact cloud model that succeeded (e.g. "gemini-3.8-flash" or "gemini-3.5-flash-lite")
  visualDiagramSvg?: string | null; // Optional legacy inline SVG diagram
  generatedDiagramUrl?: string | null; // Optional legacy image fallback
  completedAt: TimestampLike;
}

// Collection: fieldLogs/{logId}
export interface FieldLog {
  id: string;
  userId: string;
  domain: FieldDomain;
  title: string; // Auto-generated by Gemini Nano on-device
  rawInput: string; // Farmer/Engineer field observation
  imageBase64?: string | null; // Optional compressed JPEG (<150KB) for offline multimodal triage + sync
  locationTag: string; // e.g., "Cassava Plot 2" or "Retaining Wall North"

  // Immediate On-Device AI Output (Gemini Nano / Fallback)
  localTriage: LocalTriageResult | null;

  // Heavy Cloud Escalation (Cloud Gemini 3.8 Flash)
  cloudAuditStatus: "none" | "queued_offline" | "processing" | "completed" | "failed";
  cloudAuditError?: string | null;
  cloudAudit: CloudAuditResult | null;

  isSyncedToCloud: boolean; // Derived from Firestore snapshot metadata.fromCache
  createdAt: TimestampLike;
}

// Collection: synthesisReports/{reportId}
export interface SynthesisReport {
  id: string;
  userId: string;
  domain: FieldDomain;
  logIdsIncluded: string[];
  executiveSummary: string;
  priorityChecklist: Array<{
    task: string;
    urgency: "immediate" | "this_week" | "monitor";
    completed: boolean;
  }>;
  consolidatedMaterials: Array<{
    item: string;
    totalQuantity: string;
    targetZones: string;
  }>;
  modelUsed?: string; // Exact cloud model that succeeded
  createdAt: TimestampLike;
}

export interface RemoteConfigValues {
  agri_system_prompt: string;
  construction_system_prompt: string;
  active_cloud_model: string;
  triage_max_tokens: number;
  prompt_config_version: string;
  auto_queue_critical_logs: boolean;
  agri_audit_template_id: string;
  agri_synthesis_template_id: string;
  agri_voice_template_id: string;
  site_audit_template_id: string;
  site_synthesis_template_id: string;
  site_voice_template_id: string;
  source: "remote" | "cached" | "default";
  lastFetchedAt: number | null;
}

export interface InlineMediaInput {
  data: string; // Raw base64 without data: prefix
  mimeType: string;
  name?: string;
  sizeBytes?: number;
}

export interface AppCheckTelemetry {
  initialized: boolean;
  verified: boolean;
  mode: "debug_token" | "recaptcha_enterprise" | "uninitialized";
  message: string;
}
